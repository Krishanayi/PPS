/** Arithmetic Operations */
#include<stdio.h>
int main()
{
     int a;
     int b;
  printf("\n Enter the value of a and b");
  scanf("%d %d", &a, &b);

  printf("\n Add=%d", a+b);
  printf("\n Sub=%d", a-b);
  printf("\n Mul=%d", a*b);
  printf("\n Div=%d", a/b);
  printf("\n Rem=%d", a%b);

return 0;
}
